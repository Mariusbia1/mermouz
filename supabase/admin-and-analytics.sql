-- 1. Table des administrateurs basée sur l'ID utilisateur (ne casse jamais
--    quand vous changez d'adresse email dans Paramètres)
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

-- Enregistre automatiquement les comptes existants dans auth.users comme admins
-- (pour un portfolio personnel mono-admin ; vous pouvez retirer un compte si besoin)
insert into public.admin_users (user_id, email)
select id, email from auth.users
on conflict (user_id) do update set email = excluded.email;

-- Fonction de vérification admin basée sur user_id OU email
create or replace function public.is_portfolio_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    exists (
      select 1
      from public.admin_users
      where user_id = (select auth.uid())
    )
    or lower(coalesce((select auth.jwt() ->> 'email'), '')) in (
      'mariusbiaou75@gmail.com'
    );
$$;

revoke all on function public.is_portfolio_admin() from public;
grant execute on function public.is_portfolio_admin() to authenticated;

drop policy if exists "L’administrateur lit la liste admin" on public.admin_users;
create policy "L’administrateur lit la liste admin"
  on public.admin_users for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_portfolio_admin()));

-- 2. Garantit que site_settings existe et que les politiques RLS sont propres
create table if not exists public.site_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.site_settings enable row level security;

drop policy if exists "Les contenus sont visibles par tous" on public.site_settings;
drop policy if exists "L’administrateur gère les contenus" on public.site_settings;

create policy "Les contenus sont visibles par tous"
  on public.site_settings for select to anon, authenticated
  using (true);

create policy "L’administrateur gère les contenus"
  on public.site_settings for all to authenticated
  using ((select public.is_portfolio_admin()))
  with check ((select public.is_portfolio_admin()));

-- 3. Enrichissement de website_visits (appareil, navigateur, taille écran)
alter table public.website_visits
  add column if not exists device_type text,
  add column if not exists browser text,
  add column if not exists screen_size text;

drop policy if exists "L’administrateur consulte les visites" on public.website_visits;
create policy "L’administrateur consulte les visites"
  on public.website_visits for select to authenticated
  using ((select public.is_portfolio_admin()));

drop policy if exists "L’administrateur supprime les visites" on public.website_visits;
create policy "L’administrateur supprime les visites"
  on public.website_visits for delete to authenticated
  using ((select public.is_portfolio_admin()));

-- 4. Nouvelle table visitor_events : toutes les actions menées par chaque visiteur
create table if not exists public.visitor_events (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  session_id text,
  event_type text not null,
  event_label text,
  page_path text not null default '/',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists visitor_events_visitor_idx
  on public.visitor_events (visitor_id, created_at desc);
create index if not exists visitor_events_date_idx
  on public.visitor_events (created_at desc);
create index if not exists visitor_events_type_idx
  on public.visitor_events (event_type);

alter table public.visitor_events enable row level security;

drop policy if exists "Le public peut enregistrer une action" on public.visitor_events;
drop policy if exists "L’administrateur consulte les actions" on public.visitor_events;
drop policy if exists "L’administrateur supprime les actions" on public.visitor_events;

create policy "Le public peut enregistrer une action"
  on public.visitor_events for insert to anon, authenticated
  with check (true);

create policy "L’administrateur consulte les actions"
  on public.visitor_events for select to authenticated
  using ((select public.is_portfolio_admin()));

create policy "L’administrateur supprime les actions"
  on public.visitor_events for delete to authenticated
  using ((select public.is_portfolio_admin()));

-- 5. Garantit les permissions sur get_public_visit_stats
grant execute on function public.get_public_visit_stats() to authenticated;
